    <h2>Amigos e famílias na sociedade</h2>
    <p>Nos primeiros anos, Vicente Faria foi convidado a entrar na sociedade, mas havia entre ele e os irmãos um acordo de dedicação exclusiva à Empresa São Gonçalo, de transporte coletivo, fundada em Contagem por seu pai, José Faria da Rocha. Sem poder aceitar, Vicente indicou Luiz da Cunha, o Luizinho. Não foi por acaso: todos eram amigos e as famílias sempre foram próximas.</p>
    <p>Em 2004, Vicente passou a integrar efetivamente a sociedade, ao lado de Carlos e Luizinho. Por volta de 2010, Luizinho deixou a sociedade e vendeu sua participação a Vicente e Carlos.</p>
    <h2>1995: a casa própria e a tele-entrega</h2>
    <p>De 1977 a 1995 a Bianca ficou em seu primeiro endereço. Em 1995 mudou-se para o imóvel onde está até hoje, uma sede construída para ser a Pizzaria Bianca, com identidade própria e espaço para crescer.</p>
    <p>Foi nessa mudança que começou a tele-entrega, o que hoje chamamos de delivery. Não havia internet, os telefones eram caros e pouco acessíveis, e as rotas eram feitas com mapas e muito conhecimento das ruas da cidade. Uma operação desafiadora e visionária.</p>
    <p>O prédio guarda marcas dessa época: parte do desnível interno que separa o salão das áreas de produção nasceu das limitações financeiras da construção.</p>
